interface GeminiMessage {
  role: 'user' | 'model';
  parts: { text: string }[];
}

interface GeminiResponse {
  candidates?: {
    content?: {
      parts?: { text?: string }[];
    };
  }[];
  error?: { message: string };
}

export async function sendToGemini(
  userMessage: string,
  history: { role: 'user' | 'bot'; content: string }[]
): Promise<string> {
  // إذا لم يتم تكوين المفتاح - نرجع للردود المحلية
  if (!GEMINI_API_KEY) {
    console.warn('⚠️ لم يتم تكوين مفتاح Gemini API. استخدم الردود المحلية.');
    return getLocalSmartReply(userMessage);
  }

  const API_URL = `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent?key=${GEMINI_API_KEY}`;

  // تحويل تاريخ المحادثة لتنسيق Gemini
  const geminiHistory: GeminiMessage[] = history
    .filter(msg => msg.content.trim())
    .map(msg => ({
      role: msg.role === 'user' ? 'user' : 'model',
      parts: [{ text: msg.content }]
    }));

  const body = {
    contents: [...geminiHistory, {
      role: 'user',
      parts: [{ text: userMessage }]
    }],
    systemInstruction: {
      parts: [{ text: SYSTEM_INSTRUCTION }]
    },
    generationConfig: {
      temperature: 0.8,
      maxOutputTokens: 500,
    }
  };

  try {
    const response = await fetch(API_URL, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body)
    });

    if (!response.ok) {
      const errorData = await response.json();
      console.error('Gemini API Error:', errorData);
      throw new Error(errorData?.error?.message || 'API Error');
    }

    const data: GeminiResponse = await response.json();
    const reply = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    
    if (!reply) {
      throw new Error('Empty response from Gemini');
    }
    return reply;
  } catch (error) {
    console.error('Gemini connection error:', error);
    // الاحتياطي: نرجع للردود المحلية
    return getLocalSmartReply(userMessage) + '\n\n(ملاحظة: يوجد حالياً مشكلة في الاتصال بالذكاء الاصطناعي، هذه إجابة من قاعدة البيانات المحلية.)';
  }
}

